/* ecc_p384_kat.h - deterministic ECDSA P-384 (SECP384R1) known-answer vector.
 *
 * Source: RFC 6979 Appendix A.2.6 (P-384), message "sample", hash SHA-384.
 * The same vector wolfCrypt's own ecc384_test_deterministic_k() uses.  The
 * digest is not stored: the device hashes "sample" with SHA-384 itself, so the
 * KAT covers the hash-to-verify chain rather than just the curve math.
 *
 * Brace-init byte arrays (NOT "\x.." string literals): on cl2000 a char[]/byte[]
 * initialized from a "\x.." string sign-extends bytes >= 0x80 into the 16-bit
 * cell; a brace-init list stores clean octets.
 */
